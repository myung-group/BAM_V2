"""Write race_v2_torch/data/element_tables.json from the JAX sources, without importing them (no jax needed):

  uff_vdw[Z]        = (x_I [A], D_I [eV], zeta_I)       race_v2/models/race.py UFF_VDW (expressions evaluated in Python)
  covalent_radii[Z] = R [A]                           race_v2/training/train.py COVALENT_RADII
  shell_radii[Z]    = <r> of the outermost s, p, d, f shell in A (0 = absent), r_mean * BOHR_A as
                      training.train.element_shell_radii (from race_v2/models/atomic_shells.json)

    python race_v2_torch/tools/make_element_tables.py [--repo /scratch/t510a13/BAM_V2_merged]
"""
import argparse
import ast
import json
from pathlib import Path

ap = argparse.ArgumentParser()
ap.add_argument('--repo', default=str(Path(__file__).resolve().parents[2]))
a = ap.parse_args()
repo = Path(a.repo)


def module_assign(path, name):
    tree = ast.parse(open(path).read())
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == name for t in node.targets):
            return node.value
    raise KeyError(name)


def eval_node(node):
    # literal dicts / tuples with arithmetic (e.g. 0.044 * 0.0433641), evaluated exactly as Python does at import
    return eval(compile(ast.Expression(node), '<table>', 'eval'), {'__builtins__': {}})


uff = eval_node(module_assign(repo / 'race_v2/models/race.py', 'UFF_VDW'))
cov = eval_node(module_assign(repo / 'race_v2/training/train.py', 'COVALENT_RADII'))
bohr = eval_node(module_assign(repo / 'race_v2/training/train.py', 'BOHR_A'))
shell_l = eval_node(module_assign(repo / 'race_v2/training/train.py', 'SHELL_L'))
table = json.load(open(repo / 'race_v2/models/atomic_shells.json'))
shells = {}
for z, entry in table.items():
    sh = entry['shells']
    shells[int(z)] = [0.0 if sh[name] is None else sh[name]['r_mean'] * bohr for name in shell_l]

out = {
    'note': 'generated by race_v2_torch/tools/make_element_tables.py from race_v2/models/race.py (UFF_VDW), '
            'race_v2/training/train.py (COVALENT_RADII, BOHR_A, SHELL_L) and race_v2/models/atomic_shells.json',
    'bohr_angstrom': bohr,
    'shell_l': shell_l,
    'uff_vdw': {str(z): [float(v) for v in uff[z]] for z in sorted(uff)},
    'covalent_radii': {str(z): float(cov[z]) for z in sorted(cov)},
    'shell_radii': {str(z): shells[z] for z in sorted(shells)},
}
dst = Path(__file__).resolve().parents[1] / 'race_v2_torch' / 'data' / 'element_tables.json'
dst.parent.mkdir(parents=True, exist_ok=True)
json.dump(out, open(dst, 'w'), indent=1)
print(f'{dst}: {len(out["uff_vdw"])} UFF rows, {len(out["covalent_radii"])} radii, {len(out["shell_radii"])} shell rows')
